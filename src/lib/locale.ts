export function normalizeLocale(value?: string | null): AppLocale {
	return value === "zh" ? "zh" : "en";
}

export function getDictionary(locale: AppLocale) {
	return dictionaries[locale];
}

function getIntlLocale(locale: AppLocale) {
	return locale === "zh" ? "zh-CN" : "en-US";
}

export function formatLocaleDate(
	value: Date | string,
	locale: AppLocale,
) {
	const date = value instanceof Date ? value : new Date(value);
	return new Intl.DateTimeFormat(getIntlLocale(locale), {
		year: "numeric",
		month: "2-digit",
		day: "2-digit",
	}).format(date);
}

export function formatLocaleDateTime(
	value: Date | string,
	locale: AppLocale,
) {
	const date = value instanceof Date ? value : new Date(value);
	return new Intl.DateTimeFormat(getIntlLocale(locale), {
		year: locale === "zh" ? "numeric" : undefined,
		month: locale === "zh" ? "2-digit" : "short",
		day: "numeric",
		hour: "2-digit",
		minute: "2-digit",
		hour12: locale !== "zh",
	}).format(date);
}

export function formatLocaleWeekday(
	value: Date | string,
	locale: AppLocale,
) {
	const date = value instanceof Date ? value : new Date(value);
	return new Intl.DateTimeFormat(getIntlLocale(locale), {
		weekday: "short",
	}).format(date);
}
